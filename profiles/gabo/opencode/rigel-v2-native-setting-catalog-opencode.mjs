/**
 * `[opencode]` feature-setting half of the Rigel V2 setting catalog.
 *
 * Every entry is a key the shipped `assets/oh-my-opencode.schema.json` declares
 * and the layered `assets/omo.schema.json` repeats under its `[opencode]` block,
 * so the canonical `[opencode].<key>` spelling addresses the same leaf in both
 * the legacy flat file and `~/.omo/omo.jsonc`.
 *
 * The tier records what the native V2 runtime ACTUALLY does with the key:
 *
 *   - `live`: re-read from the user+project chain at runtime (`resolveNative*`).
 *   - `baked`: materialized into the installed agent manifest at install time
 *     (`profiles/gabo/build-target-agent-manifest.mjs`), so an edit lands on the
 *     next reinstall and nothing before that.
 *   - `inert`: schema-backed, but no reader in the native V2 runtime. The
 *     evidence names the reason: outside `TARGET_KEYS` (never reaches the plugin
 *     view), a quarantined surface, a profile contract that refuses it, or a
 *     V1-only host `context.config` that V2 does not expose.
 *   - `engine`: consumed by the engine / sibling-harness layer, never by this
 *     adapter.
 *
 * The budget and limit leaves of `monitor`, `team_mode` and `experimental` live
 * in `rigel-v2-native-setting-catalog-opencode-limits.mjs`; this file carries the
 * feature, denylist, category and agent surface.
 *
 * `validation` is the canonical projection of the schema node (type, default,
 * bounds, enum, item type, required list) and is pinned against BOTH shipped
 * schemas by `rigel-v2-native-setting-catalog.parity.test.mjs`.
 */
